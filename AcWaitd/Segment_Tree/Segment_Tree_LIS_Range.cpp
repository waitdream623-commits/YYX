// ================================================================
// 区间最长上升子序列 / 子数组 — 文件索引
// ================================================================
//
// 两种问题，已拆分为独立文件：
//
// ┌─ Segment_Tree_LCIS.cpp  — 连续上升子数组（LCIS）
// │   元素必须相邻，线段树 merge，O(log n) 查询，支持单点修改
// │   示例：[3,4,8] ✓    [3,5,8] ✗ （5跳过了4不连续）
// │
// └─ Range_LIS.cpp         — 上升子序列（LIS，不连续）
//     可跳着选，patience sorting，O(k log k) 每次查询
//     示例：[1,5,3,4,8] 可选出 [1,3,4,8] 长度 4
//
// 对照表：
// ┌──────────┬────────────────────┬──────────────────┐
// │          │  连续上升 (LCIS)   │ 子序列 LIS (不连续)│
// ├──────────┼────────────────────┼──────────────────┤
// │ 相邻要求 │  必须相邻          │  可跳着选        │
// │ 查询复杂度│ O(log n)          │  O(k log k)     │
// │ 单点修改 │  支持 O(log n)     │  不支持          │
// │ 数据范围 │  n,q ≤ 1e5        │  n,q ≤ 5000     │
// │ 文件     │ Segment_Tree_LCIS │  Range_LIS       │
// └──────────┴────────────────────┴──────────────────┘
// ================================================================

